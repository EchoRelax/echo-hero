import { createRequire } from 'node:module'
import { join } from 'node:path'
import { mkdirSync } from 'node:fs'
import assert from 'node:assert/strict'
const require = createRequire(join(process.env.TEMP, 'echo-hero-qa', 'package.json'))
const { chromium } = require('playwright')
const browser = await chromium.launch({headless:true,channel:'msedge'})
const errors=[]
mkdirSync('art/ui',{recursive:true})
for(const width of [1440,390,320]) {
 const context=await browser.newContext({viewport:{width,height:900}})
 const page=await context.newPage()
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto('http://127.0.0.1:5173/')
 await page.locator('.open-settings').waitFor()
 assert.equal(await page.locator('html').getAttribute('lang'),'ru')
 await page.locator('.open-settings').click()
 assert.equal(await page.locator('#settings-title').textContent(),'Настройки')
 assert.equal(await page.locator('.language-choice').inputValue(),'ru')
 await page.locator('.language-choice').selectOption('en')
 assert.equal(await page.locator('#settings-title').textContent(),'Settings')
 assert.equal(await page.locator('.settings-status').textContent(),'Settings saved')
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('echo-hunt-settings')).language),'en')
 await page.locator('.settings-close').click()
 await page.locator('.open-upgrades').click()
 assert.equal(await page.locator('#upgrades-title').textContent(),'Upgrades')
 assert.equal(await page.locator('.upgrade-row small').count(),0)
 assert.equal(await page.locator('.upgrade-row strong').first().textContent(),'Damage')
 await page.locator('.panel-close:visible').click()
 await page.locator('.open-settings').click()
 await page.locator('.language-choice').selectOption('ru')
 await page.screenshot({path:`art/ui/${width}-ru-settings.png`})
 await page.locator('.settings-close').click()
 await page.locator('.open-upgrades').click()
 assert.equal(await page.locator('#upgrades-title').textContent(),'Улучшения')
 assert.equal(await page.locator('.upgrade-row small').count(),0)
 assert.equal(await page.locator('.upgrade-row strong').first().textContent(),'Урон')
 assert.equal(await page.locator('.upgrade-stat-next').first().evaluate(n=>getComputedStyle(n).fontWeight),'500')
 const overflow=await page.locator('.upgrades-panel').evaluate(n=>n.scrollWidth>n.clientWidth)
 assert.equal(overflow,false,`Upgrade panel overflow at ${width}`)
 await page.screenshot({path:`art/ui/${width}-ru-upgrades.png`})
 await page.locator('.panel-close:visible').click()
 await page.locator('.open-runes').first().click()
 assert.equal(await page.locator('#rune-title').textContent(),'Руны оружия')
 assert.equal(await page.locator('.rune-detail strong').first().textContent(),'Руна корней')
 assert.match(await page.locator('.rune-detail small').first().textContent(),/Закрыто/)
 assert.equal(await page.locator('.rune-panel').evaluate(n=>n.scrollWidth>n.clientWidth),false,`Rune overflow at ${width}`)
 await page.reload()
 await page.locator('.open-settings').waitFor()
 assert.equal(await page.locator('html').getAttribute('lang'),'ru')
 await page.locator('.open-settings').click()
 await page.locator('.language-choice').selectOption('en')
 await page.reload();await page.locator('.open-settings').waitFor()
 assert.equal(await page.locator('html').getAttribute('lang'),'en')
 console.log(`${width}px: RU/EN live switch, menus, translated stats, persistence, layout passed`)
 await context.close()
}
await browser.close()
assert.deepEqual(errors,[])
