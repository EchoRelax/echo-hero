"""Prepare licensed recordings from downloaded upstream archives; no synthesis.
Requires numpy and soundfile. Archives live in .asset-downloads (not shipped).
"""
from pathlib import Path
import hashlib, io, json, zipfile
import numpy as np
import soundfile as sf

sources = {
 'swords': ('sword_-_starninjas_1', 'StarNinjas', 'https://opengameart.org/content/20-sword-sound-effects-attacks-and-clashes'),
 'rpg': ('80-CC0-RPG-SFX_0', 'rubberduck', 'https://opengameart.org/content/80-cc0-rpg-sfx'),
 'impact': ('impact-sounds', 'Kenney', 'https://kenney.nl/assets/impact-sounds'),
 'ui': ('interface-sounds', 'Kenney', 'https://kenney.nl/assets/interface-sounds'),
 'jingles': ('music-jingles', 'Kenney', 'https://kenney.nl/assets/music-jingles'),
 'foley': ('rpg-audio', 'Kenney', 'https://kenney.nl/assets/rpg-audio'),
}
selection = {
 'swing-1': ('swords', 'sword - StarNinjas/sword.4.ogg'),
 'swing-2': ('swords', 'sword - StarNinjas/sword.6.ogg'),
 'swing-3': ('swords', 'sword - StarNinjas/sword.3.ogg'),
 'hit-1': ('impact', 'Audio/impactPunch_medium_000.ogg'),
 'hit-2': ('impact', 'Audio/impactPunch_medium_001.ogg'),
 'hit-3': ('impact', 'Audio/impactPunch_medium_002.ogg'),
 'kill-1': ('impact', 'Audio/impactSoft_heavy_000.ogg'),
 'kill-2': ('impact', 'Audio/impactSoft_heavy_001.ogg'),
 'hurt': ('impact', 'Audio/impactPunch_heavy_000.ogg'),
 'gold-1': ('rpg', 'item_coins_01.ogg'),
 'gold-2': ('rpg', 'item_coins_03.ogg'),
 'xp-1': ('rpg', 'item_gem_01.ogg'),
 'xp-2': ('rpg', 'item_gem_02.ogg'),
 'level': ('jingles', 'Audio/Pizzicato jingles/jingles_PIZZI01.ogg'),
 'victory': ('jingles', 'Audio/Pizzicato jingles/jingles_PIZZI07.ogg'),
 'buy': ('ui', 'Audio/confirmation_002.ogg'),
 'equip': ('foley', 'Audio/drawKnife1.ogg'),
 'click': ('ui', 'Audio/click_001.ogg'),
 'warning': ('ui', 'Audio/question_001.ogg'),
 'death': ('ui', 'Audio/error_005.ogg'),
 'root-1': ('rpg', 'wood_04.ogg'),
 'root-2': ('rpg', 'wood_05.ogg'),
 'fire-1': ('rpg', 'spell_fire_06.ogg'),
 'fire-2': ('rpg', 'spell_fire_07.ogg'),
 'lightning-1': ('rpg', 'spell_01.ogg'),
 'lightning-2': ('rpg', 'spell_02.ogg'),
 'step-1': ('impact', 'Audio/footstep_grass_000.ogg'),
 'step-2': ('impact', 'Audio/footstep_grass_001.ogg'),
 'step-3': ('impact', 'Audio/footstep_grass_002.ogg'),
}
root = Path(__file__).resolve().parents[1]
out = root / 'public/audio'
out.mkdir(parents=True, exist_ok=True)
records = []
for name, (source, member) in selection.items():
 archive, author, page = sources[source]
 with zipfile.ZipFile(root / '.asset-downloads' / (archive + '.zip')) as z:
  original = z.read(member)
  if 'License.txt' in z.namelist():
   (out / (source + '-LICENSE.txt')).write_bytes(z.read('License.txt'))
 data, rate = sf.read(io.BytesIO(original), dtype='float32', always_2d=True)
 data = data.mean(axis=1)
 # Remove only silence around the existing recording, leaving a 5ms margin.
 active = np.flatnonzero(np.abs(data) > 0.002)
 if len(active): data = data[max(0, active[0]-int(rate*.005)):min(len(data),active[-1]+int(rate*.015)+1)]
 rms = float(np.sqrt(np.mean(data*data)))
 peak = float(np.max(np.abs(data)))
 data *= min(0.8 / max(peak, 1e-6), 0.09 / max(rms, 1e-6), 3.0)
 fade = min(int(rate*.003), len(data)//2)
 data[:fade] *= np.linspace(0,1,fade)
 data[-fade:] *= np.linspace(1,0,fade)
 dest = out / (name+'.wav')
 sf.write(dest, data, rate, subtype='PCM_16')
 records.append({'file':dest.name,'author':author,'source':page,'archive':archive+'.zip','original':member,'license':'CC0-1.0','original_sha256':hashlib.sha256(original).hexdigest(),'sha256':hashlib.sha256(dest.read_bytes()).hexdigest(),'seconds':round(len(data)/rate,3)})
(out/'provenance.json').write_text(json.dumps(records,indent=2)+'\n',encoding='utf-8')
(out/'CREDITS.md').write_text('# Audio credits\n\nAll effects are sourced recordings under CC0 1.0, not generated by the game.\n\n'+ '\n'.join(f'- {author}: [{name}]({page}) — CC0 1.0.' for name,(_,author,page) in sources.items())+'\n\nLicense: https://creativecommons.org/publicdomain/zero/1.0/\n\nEdits: mono downmix, silence trimming, gain matching, 3ms edge fades, PCM WAV conversion. No new sounds synthesized. Exact source files and hashes are in provenance.json.\n',encoding='utf-8')
print(f'{len(records)} recordings, {sum(p.stat().st_size for p in out.glob("*.wav")) / 1024:.0f} KiB')
